'use webmcp-tool v1';

const YOUTUBE_ORIGIN = 'https://www.youtube.com';
const TRANSCRIPT_PANEL_TARGET = 'engagement-panel-searchable-transcript';
const TRANSCRIPT_LOAD_TIMEOUT_MS = 5_000;
const TRANSCRIPT_CANCEL_CLEANUP_TIMEOUT_MS = 500;
const VIDEO_CHANGED_ERROR = 'YouTube video changed while retrieving transcript';

let transcriptPanelLoad = null;

export const metadata = {
  name: 'youtube_transcript',
  namespace: 'agentboard',
  version: '1.1.0',
  description:
    "Get the current YouTube video's transcript with timestamps and metadata. Retrieval may briefly open and close YouTube's transcript panel.",
  match: ['*://www.youtube.com/watch*', '*://youtube.com/watch*'],
  inputSchema: {
    type: 'object',
    properties: {
      language: {
        type: 'string',
        description:
          'Preferred language code (e.g., "en", "es"). Defaults to English or first available.',
      },
      format: {
        type: 'string',
        enum: ['segments', 'text'],
        description:
          '"segments" returns timestamped array, "text" returns concatenated plain text. Default: "segments"',
      },
    },
    additionalProperties: false,
  },
};

export async function execute(args = {}, { signal } = {}) {
  signal?.throwIfAborted();
  const videoId = currentVideoId();
  if (!videoId) {
    return failure(null, 'Not on a YouTube video page (no video ID found)');
  }

  const playerResponse = resolvePlayerResponse(videoId);
  if (!playerResponse) {
    return failure(null, 'Could not retrieve current video data from YouTube');
  }
  const videoDetails = playerResponse.videoDetails || {};
  const metadata = {
    videoId,
    title: videoDetails.title || '',
    author: videoDetails.author || '',
    channelId: videoDetails.channelId || '',
    lengthSeconds: parseInt(videoDetails.lengthSeconds, 10) || 0,
    viewCount: parseInt(videoDetails.viewCount, 10) || 0,
    description: videoDetails.shortDescription || '',
    keywords: videoDetails.keywords || [],
    isLive: videoDetails.isLiveContent || false,
  };

  const captionTracks = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
  if (!captionTracks?.length) {
    return failure(metadata, 'No captions available for this video');
  }

  // Prefer manual captions over auto-generated (ASR) captions.
  const manualTracks = captionTracks.filter((track) => !track.kind);
  const tracksToSearch = manualTracks.length > 0 ? manualTracks : captionTracks;
  const preferredLanguage = args.language || 'en';
  const selectedTrack =
    tracksToSearch.find((track) => track.languageCode === preferredLanguage) ||
    tracksToSearch.find((track) => track.languageCode.startsWith(preferredLanguage)) ||
    tracksToSearch.find((track) => track.languageCode.startsWith('en')) ||
    tracksToSearch[0];

  // Legacy timed-text remains the cheapest path and does not touch page UI. Newer
  // Gemini-generated captions can expose a valid track while returning an empty
  // timed-text body, so delegate the protected fallback to YouTube's own UI flow.
  let track = selectedTrack;
  let segments = await fetchTimedTextSegments(selectedTrack, signal);
  signal?.throwIfAborted();
  const warnings = [];
  if (segments.length === 0) {
    const loaded = await loadTranscriptPanel(videoId, signal);
    signal?.throwIfAborted();
    if (loaded.error) {
      return failure(metadata, loaded.error);
    }
    // Attribute against this call's own player data: the shared panel load may have been
    // created by a concurrent call holding different track objects for the same video.
    track = captionTracks.find((candidate) => encodeTrackParams(candidate) === loaded.trackParams);
    if (!track) {
      return failure(
        metadata,
        "YouTube's transcript panel loaded a caption track that matches none of this video's " +
          `caption tracks (${languageCodes(captionTracks)})`
      );
    }
    segments = loaded.segments;
    if (track !== selectedTrack) {
      // The panel opens the video's default track and offers no way to request another one
      // short of driving its language menu. On multi-audio (auto-dubbed) videos that default
      // is the original-language transcript, a better source than ASR of a machine dub, so
      // return it and state the substitution rather than failing.
      warnings.push(
        `YouTube's transcript panel loaded caption track ${describeTrack(track)} instead of the ` +
          `selected track ${describeTrack(selectedTrack)}. Caption tracks on this video: ` +
          `${languageCodes(captionTracks)}.`
      );
    }
  }
  if (currentVideoId() !== videoId) {
    return failure(metadata, VIDEO_CHANGED_ERROR);
  }

  const transcript = {
    language: track.languageCode,
    languageName: textFromRuns(track.name) || track.languageCode,
    isAutoGenerated: track.kind === 'asr',
    segmentCount: segments.length,
  };

  if (args.format === 'text') {
    transcript.text = segments.map((segment) => segment.text).join(' ');
  } else {
    transcript.segments = segments;
  }

  const result = { metadata, transcript };
  if (warnings.length > 0) {
    result.warnings = warnings;
  }
  return result;
}

/**
 * Expected failures travel in the result, never as a rejection. WebMCP maps every callback
 * rejection to a bare UnknownError (Chrome's native implementation and the polyfill alike), so
 * a thrown message can never reach the model. Only abort is allowed to reject.
 */
function failure(metadata, error) {
  return { metadata, transcript: null, error };
}

function describeTrack(track) {
  const name = textFromRuns(track.name);
  return name ? `${track.languageCode} (${name})` : track.languageCode;
}

function languageCodes(tracks) {
  return tracks.map((track) => track.languageCode).join(', ');
}

function currentVideoId() {
  return new URL(window.location.href).searchParams.get('v');
}

/**
 * Prefer the live player because it follows same-document YouTube navigation.
 * Every page-derived response is fenced to the URL's current video ID before it
 * can supply metadata, caption URLs, or transcript authority.
 */
function resolvePlayerResponse(videoId) {
  const player = document.getElementById('movie_player');
  const candidates = [];

  if (typeof player?.getPlayerResponse === 'function') {
    try {
      candidates.push(player.getPlayerResponse());
    } catch {
      // The player can exist before its API is ready; the initial response may be usable.
    }
  }
  candidates.push(window.ytInitialPlayerResponse);

  const matchingResponses = candidates.filter(
    (response) => response?.videoDetails?.videoId === videoId
  );
  const responseWithCaptions = matchingResponses.find(
    (response) => response?.captions?.playerCaptionsTracklistRenderer?.captionTracks?.length > 0
  );
  return responseWithCaptions || matchingResponses[0] || null;
}

async function fetchTimedTextSegments(track, signal) {
  signal?.throwIfAborted();
  try {
    const transcriptUrl = new URL(track.baseUrl, YOUTUBE_ORIGIN);
    if (transcriptUrl.origin !== YOUTUBE_ORIGIN || transcriptUrl.pathname !== '/api/timedtext') {
      return [];
    }
    transcriptUrl.searchParams.set('fmt', 'json3');

    const response = await fetch(transcriptUrl, { credentials: 'include', signal });
    if (!response.ok) {
      return [];
    }

    const body = await response.text();
    signal?.throwIfAborted();
    if (!body.trim()) {
      return [];
    }

    return parseTimedTextJson(JSON.parse(body));
  } catch {
    signal?.throwIfAborted();
    return [];
  }
}

/**
 * YouTube's transcript endpoint now requires page-generated attestation and session
 * context. Let the site's own command load that data, then restore panel visibility,
 * rather than reading cookies or replaying opaque authorization material.
 *
 * Resolves to `{ trackParams, segments }` for whichever caption track the panel loaded, or to
 * `{ error }` describing why nothing usable loaded. Only abort rejects. The load is shared per
 * video, not per track: the panel decides the track, and each caller attributes the result.
 */
async function loadTranscriptPanel(videoId, signal) {
  signal?.throwIfAborted();
  if (transcriptPanelLoad?.controller.signal.aborted) {
    try {
      await transcriptPanelLoad.promise;
    } catch {
      // The cancelled owner keeps the slot until its panel cleanup finishes.
    }
    signal?.throwIfAborted();
    return loadTranscriptPanel(videoId, signal);
  }

  const loaded = readTranscriptPanel(videoId);
  if (loaded) {
    return loaded;
  }

  if (transcriptPanelLoad) {
    if (transcriptPanelLoad.videoId !== videoId) {
      return {
        error:
          "YouTube's transcript panel is still loading a transcript for a different video in this tab",
      };
    }
    return consumeTranscriptPanelLoad(transcriptPanelLoad, signal);
  }

  const controller = new AbortController();
  const load = { videoId, controller, consumers: 0, promise: null };
  transcriptPanelLoad = load;
  // Deferral installs the first consumer before the click can synchronously re-enter page code.
  load.promise = Promise.resolve()
    .then(() => openAndReadTranscriptPanel(videoId, controller.signal))
    .finally(() => {
      if (transcriptPanelLoad === load) transcriptPanelLoad = null;
    });
  return consumeTranscriptPanelLoad(load, signal);
}

function consumeTranscriptPanelLoad(load, signal) {
  signal?.throwIfAborted();
  load.consumers += 1;

  return new Promise((resolve, reject) => {
    let settled = false;
    const finish = (callback, value, cancelled = false) => {
      if (settled) return;
      settled = true;
      signal?.removeEventListener('abort', onAbort);
      load.consumers -= 1;
      if (cancelled && load.consumers === 0 && !load.controller.signal.aborted) {
        load.controller.abort(value);
      }
      callback(value);
    };
    const onAbort = () => finish(reject, signal.reason, true);

    signal?.addEventListener('abort', onAbort, { once: true });
    load.promise.then(
      (outcome) => finish(resolve, outcome),
      (error) => finish(reject, error)
    );
  });
}

async function openAndReadTranscriptPanel(videoId, signal) {
  signal.throwIfAborted();
  const expandedPanel = findExpandedEngagementPanel();
  if (expandedPanel && !isTranscriptPanel(expandedPanel)) {
    // Do not replace a panel the user is actively viewing.
    return {
      error:
        "Did not open YouTube's transcript panel because a different panel is open in this tab",
    };
  }

  const openedByAgentBoard = !expandedPanel;
  let ownedPanel = expandedPanel;

  try {
    if (openedByAgentBoard) {
      const trigger = findTranscriptTrigger();
      if (!trigger) {
        return { error: "Could not find YouTube's transcript button on this page" };
      }
      if (currentVideoId() !== videoId) {
        return { error: VIDEO_CHANGED_ERROR };
      }
      const clickable = trigger.querySelector('button, tp-yt-paper-button') || trigger;
      clickable.click();
    }

    const result = await waitForTranscriptPanel(videoId, signal);
    ownedPanel = result.panel || ownedPanel;
    return result.outcome;
  } catch (error) {
    if (openedByAgentBoard && signal.aborted && currentVideoId() === videoId) {
      // YouTube may apply the click after the transcript wait has already observed cancellation.
      // Keep only a short cleanup observer so the panel shell can be restored without retaining the
      // five-second data observer or transferring ownership to later UI.
      ownedPanel = ownedPanel || (await waitForOpenedTranscriptPanel(videoId));
    }
    throw error;
  } finally {
    if (openedByAgentBoard && currentVideoId() === videoId) {
      const currentPanel = findExpandedEngagementPanel();
      if (ownedPanel && currentPanel === ownedPanel && isTranscriptPanel(ownedPanel)) {
        ownedPanel.querySelector('#visibility-button button')?.click();
      }
    }
  }
}

function waitForTranscriptPanel(videoId, signal) {
  return new Promise((resolve, reject) => {
    let settled = false;
    let observer;
    let timeout;
    const finish = (callback, result) => {
      if (settled) return;
      settled = true;
      if (timeout !== undefined) clearTimeout(timeout);
      observer?.disconnect();
      signal.removeEventListener('abort', onAbort);
      callback(result);
    };
    const onAbort = () => finish(reject, signal.reason);
    const check = () => {
      if (currentVideoId() !== videoId) {
        finish(resolve, { outcome: { error: VIDEO_CHANGED_ERROR }, panel: null });
        return;
      }
      const panel = findTranscriptPanelWithData(videoId);
      if (!panel) return;
      const outcome = readTranscriptPanel(videoId, panel);
      if (outcome) {
        finish(resolve, { outcome, panel });
      }
    };

    if (signal.aborted) {
      reject(signal.reason);
      return;
    }
    observer = new MutationObserver(check);
    timeout = setTimeout(
      () =>
        finish(resolve, {
          outcome: {
            error: `YouTube's transcript panel did not load a transcript within ${
              TRANSCRIPT_LOAD_TIMEOUT_MS / 1000
            } seconds`,
          },
          panel: findExpandedEngagementPanel(),
        }),
      TRANSCRIPT_LOAD_TIMEOUT_MS
    );
    signal.addEventListener('abort', onAbort, { once: true });
    observer.observe(document.documentElement, { childList: true, subtree: true });
    check();
  });
}

function waitForOpenedTranscriptPanel(videoId) {
  const findPanel = () => {
    if (currentVideoId() !== videoId) return null;
    const panel = findExpandedEngagementPanel();
    return panel && isTranscriptPanel(panel) ? panel : null;
  };
  const existingPanel = findPanel();
  if (existingPanel) return Promise.resolve(existingPanel);

  return new Promise((resolve) => {
    let settled = false;
    const finish = (panel) => {
      if (settled) return;
      settled = true;
      clearTimeout(timeout);
      observer.disconnect();
      resolve(panel);
    };
    const check = () => {
      if (currentVideoId() !== videoId) {
        finish(null);
        return;
      }
      const panel = findPanel();
      if (panel) finish(panel);
    };
    const observer = new MutationObserver(check);
    const timeout = setTimeout(() => finish(null), TRANSCRIPT_CANCEL_CLEANUP_TIMEOUT_MS);
    observer.observe(document.documentElement, {
      childList: true,
      subtree: true,
      attributes: true,
    });
    check();
  });
}

function findTranscriptTrigger() {
  return Array.from(document.querySelectorAll('ytd-button-renderer')).find((element) =>
    commandTargetsTranscript(element.data?.command)
  );
}

function commandTargetsTranscript(command) {
  const seen = new WeakSet();
  let visited = 0;

  function visit(value, depth) {
    if (typeof value === 'string') {
      return value.startsWith(TRANSCRIPT_PANEL_TARGET);
    }
    if (
      value === null ||
      typeof value !== 'object' ||
      depth > 12 ||
      visited++ > 2_000 ||
      seen.has(value)
    ) {
      return false;
    }

    seen.add(value);
    return Object.values(value).some((child) => visit(child, depth + 1));
  }

  return visit(command, 0);
}

function findExpandedEngagementPanel() {
  return Array.from(document.querySelectorAll('ytd-engagement-panel-section-list-renderer')).find(
    (panel) => panel.getAttribute('visibility') === 'ENGAGEMENT_PANEL_VISIBILITY_EXPANDED'
  );
}

function isTranscriptPanel(panel) {
  return (
    panel.getAttribute('target-id')?.includes('transcript') ||
    panel.querySelector('ytd-transcript-segment-list-renderer') !== null
  );
}

function findTranscriptPanelWithData(videoId) {
  const panels = Array.from(
    document.querySelectorAll('ytd-engagement-panel-section-list-renderer')
  ).filter((panel) => panel.querySelector('ytd-transcript-segment-list-renderer'));
  const expandedPanel = findExpandedEngagementPanel();
  panels.sort((left, right) => Number(right === expandedPanel) - Number(left === expandedPanel));

  return (
    panels.find((panel) =>
      transcriptPanelItems(panel).some((item) => {
        const targetId = item?.transcriptSegmentRenderer?.targetId;
        return typeof targetId === 'string' && targetId.startsWith(`${videoId}.`);
      })
    ) || null
  );
}

/**
 * Read whichever caption track the panel currently shows for this video. YouTube keys every
 * segment as `<videoId>.<trackParams>.<startMs>.<endMs>`; neither the ID nor the URL-encoded
 * params can contain a dot, so the track is recoverable from the first segment alone and the
 * caller matches it against the player's track list via encodeTrackParams.
 *
 * Returns `{ trackParams, segments }`, or null when the panel holds no usable data for this
 * video yet.
 */
function readTranscriptPanel(videoId, preferredPanel = null) {
  const panel = preferredPanel || findTranscriptPanelWithData(videoId);
  if (!panel) {
    return null;
  }

  const videoPrefix = `${videoId}.`;
  const renderers = transcriptPanelItems(panel)
    .map((item) => item?.transcriptSegmentRenderer)
    .filter(
      (renderer) =>
        typeof renderer?.targetId === 'string' && renderer.targetId.startsWith(videoPrefix)
    );
  if (renderers.length === 0) {
    return null;
  }

  const trackParams = renderers[0].targetId.slice(videoPrefix.length).split('.')[0];
  const trackPrefix = `${videoPrefix}${trackParams}.`;
  const segments = [];
  for (const renderer of renderers) {
    if (!renderer.targetId.startsWith(trackPrefix)) continue;
    const startMs = Number(renderer.startMs);
    const endMs = Number(renderer.endMs);
    const text = textFromRuns(renderer.snippet).trim();
    if (Number.isFinite(startMs) && Number.isFinite(endMs) && text) {
      segments.push({
        start: startMs / 1000,
        duration: Math.max(0, endMs - startMs) / 1000,
        text,
      });
    }
  }
  return segments.length > 0 ? { trackParams, segments } : null;
}

function transcriptPanelItems(panel) {
  const list = panel.querySelector('ytd-transcript-segment-list-renderer');
  const items = list?.data?.initialSegments;
  if (Array.isArray(items)) {
    return items;
  }

  return Array.from(list?.querySelectorAll('ytd-transcript-segment-renderer') || []).map(
    (element) => ({ transcriptSegmentRenderer: element.data })
  );
}

function encodeTrackParams(track) {
  const bytes = [];
  for (const [fieldNumber, value] of [
    [1, track.kind || ''],
    [2, track.languageCode],
    [3, track.trackName || ''],
  ]) {
    const encoded = new TextEncoder().encode(value);
    bytes.push((fieldNumber << 3) | 2, ...encodeVarint(encoded.length), ...encoded);
  }

  let binary = '';
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return encodeURIComponent(btoa(binary));
}

function encodeVarint(value) {
  const bytes = [];
  do {
    let byte = value & 0x7f;
    value = Math.floor(value / 128);
    if (value > 0) byte |= 0x80;
    bytes.push(byte);
  } while (value > 0);
  return bytes;
}

/** Parse the legacy timed-text JSON3 representation. */
function parseTimedTextJson(data) {
  const segments = [];
  if (!Array.isArray(data?.events)) {
    return segments;
  }

  for (const event of data.events) {
    if (!Array.isArray(event.segs)) continue;

    const text = event.segs
      .map((segment) => segment.utf8 || '')
      .join('')
      .trim();
    if (!text) continue;

    segments.push({
      start: (event.tStartMs || 0) / 1000,
      duration: (event.dDurationMs || 0) / 1000,
      text,
    });
  }
  return segments;
}

function textFromRuns(value) {
  if (typeof value?.simpleText === 'string') {
    return value.simpleText;
  }
  if (Array.isArray(value?.runs)) {
    return value.runs.map((run) => run?.text || '').join('');
  }
  return '';
}
